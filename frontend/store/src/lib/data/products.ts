export const getProductById = (id: string): Product | undefined => {
  return products.find(p => p.id === id);
};

export const getProductsByCategory = (slug: string): Product[] => {
  return products.filter(p => {
    const catSlug = typeof p.category === 'string' ? p.category : (p.category as any)?.slug;
    return catSlug === slug;
  });
};

export const getPopularProducts = (): Product[] => {
  return products.filter(p => p.isPopular);
};

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase();
  return products.filter(p => p.name.toLowerCase().includes(q) || (p.tamilName && p.tamilName.includes(q)));
};
